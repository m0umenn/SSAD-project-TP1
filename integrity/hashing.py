"""Hashing and integrity protection utilities for SSAD Toolkit (Part 4).

This module contains fast hash generation, salted PBKDF2 hashing, record
parsing, constant-time comparison helpers, and timing estimation.
It relies strictly on the Python standard library and does not import from
passwords/ or gui/.
"""

from __future__ import annotations

import hashlib
import hmac
import os
from typing import Any

ITERATIONS: int = 100_000
SALT_BYTES: int = 16


def hash_fast(password: str) -> str:
    """Return the SHA-256 hexadecimal digest of `password` (unprotected fast hash).

    Parameters:
        password (str): Plaintext input string to hash.

    Returns:
        str: 64-character hexadecimal SHA-256 digest.

    Raises:
        ValueError: If `password` is not a string.
    """
    if not isinstance(password, str):
        raise ValueError("Password must be a string.")
    return hashlib.sha256(password.encode("utf-8")).hexdigest()


def generate_salt(num_bytes: int = SALT_BYTES) -> bytes:
    """Generate cryptographically secure random bytes for salting.

    Parameters:
        num_bytes (int): Number of bytes to generate (defaults to SALT_BYTES = 16).

    Returns:
        bytes: Randomly generated bytes.

    Raises:
        ValueError: If `num_bytes` is not a positive integer.
    """
    if isinstance(num_bytes, bool) or not isinstance(num_bytes, int) or num_bytes <= 0:
        raise ValueError("num_bytes must be a positive integer.")
    return os.urandom(num_bytes)


def hash_protected(
    password: str,
    iterations: int = ITERATIONS,
    salt: bytes | None = None,
) -> dict[str, str | int]:
    """Hash `password` with a salt using PBKDF2-HMAC-SHA256.

    Parameters:
        password (str): The plaintext string to protect.
        iterations (int): PBKDF2 iteration count (defaults to 100_000).
        salt (bytes | None): Optional pre-generated salt bytes; if None, a new
            random salt of SALT_BYTES (16) is generated.

    Returns:
        dict[str, str | int]: {"salt": hex str, "iterations": int, "hash": hex str}

    Raises:
        ValueError: If `password` is not a string or `iterations` is not a positive integer.
    """
    if not isinstance(password, str):
        raise ValueError("Password must be a string.")
    if isinstance(iterations, bool) or not isinstance(iterations, int) or iterations <= 0:
        raise ValueError("Iterations must be a positive integer.")

    if salt is None:
        salt_bytes = generate_salt(SALT_BYTES)
    elif isinstance(salt, bytes) and salt:
        salt_bytes = salt
    else:
        raise ValueError("Salt must be non-empty bytes if provided.")

    derived = hashlib.pbkdf2_hmac(
        "sha256",
        password.encode("utf-8"),
        salt_bytes,
        iterations,
    )
    return {
        "salt": salt_bytes.hex(),
        "iterations": iterations,
        "hash": derived.hex(),
    }


def parse_record(record: Any) -> tuple[bytes, int, str]:
    """Validate a protected record dictionary and return (salt_bytes, iterations, hash_hex).

    Parameters:
        record (Any): Dictionary containing "salt", "iterations", and "hash".

    Returns:
        tuple[bytes, int, str]: Tuple of (salt_bytes, iterations, lower_case_hash_hex).

    Raises:
        ValueError: If `record` is not a dictionary or has missing/malformed fields.
    """
    if not isinstance(record, dict):
        raise ValueError("Malformed record.")
    if set(record.keys()) != {"salt", "iterations", "hash"}:
        raise ValueError("Malformed record.")

    salt_hex = record.get("salt")
    iterations = record.get("iterations")
    hash_hex = record.get("hash")

    if not isinstance(salt_hex, str) or not salt_hex:
        raise ValueError("Malformed record.")
    if isinstance(iterations, bool) or not isinstance(iterations, int) or iterations <= 0:
        raise ValueError("Malformed record.")
    if not isinstance(hash_hex, str) or len(hash_hex) != 64:
        raise ValueError("Malformed record.")

    try:
        salt_bytes = bytes.fromhex(salt_hex)
        bytes.fromhex(hash_hex)
    except ValueError as exc:
        raise ValueError("Malformed record.") from exc

    if not salt_bytes:
        raise ValueError("Malformed record.")

    return salt_bytes, iterations, hash_hex.lower()


def compare_hashes(a: str, b: str) -> bool:
    """Compare two hash strings in constant time to prevent timing attacks.

    Parameters:
        a (str): First string.
        b (str): Second string.

    Returns:
        bool: True if both strings match, False otherwise.
    """
    return hmac.compare_digest(a, b)


def verify_protected(password: str, record: dict[str, Any]) -> bool:
    """Verify `password` against a protected `record` using constant-time comparison.

    Parameters:
        password (str): Candidate plaintext to check.
        record (dict[str, Any]): Protected record dict with salt, iterations, and hash.

    Returns:
        bool: True if candidate matches the stored record, False otherwise.

    Raises:
        ValueError: If `password` is not a string or `record` is malformed.
    """
    if not isinstance(password, str):
        raise ValueError("Password must be a string.")
    salt_bytes, iterations, expected_hash = parse_record(record)
    derived = hashlib.pbkdf2_hmac(
        "sha256",
        password.encode("utf-8"),
        salt_bytes,
        iterations,
    ).hex()
    return compare_hashes(derived, expected_hash)


def estimate_slowdown(attempts: int, rate: float, factor: float = 1.0) -> float:
    """Calculate estimated cracking time using the slowdown formula: t = k * attempts / v.

    Parameters:
        attempts (int): Total number of password attempts / search space.
        rate (float): Checking rate v (operations per second).
        factor (float): Constant multiplier k (defaults to 1.0).

    Returns:
        float: Estimated duration in seconds, or float("inf") if rate <= 0.
    """
    if rate <= 0:
        return float("inf")
    return factor * attempts / rate
